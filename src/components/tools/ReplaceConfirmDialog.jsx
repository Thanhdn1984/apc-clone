import React from 'react';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogFooter,
  DialogClose,
} from "../../components/ui/dialog";
import { Button } from '../../components/ui/button';
import { 
  AlertCircle, FileText, Check, CheckSquare, Square,
  Link2, Wand2, MousePointerClick
} from 'lucide-react';

/**
 * Replace Confirm Dialog - Xác nhận thay thế hàng loạt (multi-file)
 */
const ReplaceConfirmDialog = ({ 
  showReplaceConfirm, 
  setShowReplaceConfirm, 
  pendingReplacements, 
  setPendingReplacements,
  pendingPlaceholder,
  pendingOldText,
  executeReplacements
}) => {
  return (
    <Dialog open={showReplaceConfirm} onOpenChange={setShowReplaceConfirm}>
      <DialogContent className="sm:max-w-2xl max-h-[80vh] overflow-hidden flex flex-col">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2 text-lg">
            <AlertCircle className="h-5 w-5 text-amber-500" />
            Xác nhận thay thế hàng loạt
          </DialogTitle>
          <DialogDescription>
            Tìm thấy <strong className="text-blue-600">{pendingReplacements.length}</strong> vị trí chứa 
            "<strong className="text-red-600">{pendingOldText}</strong>" sẽ được thay bằng 
            <code className="bg-green-100 text-green-700 px-1 rounded mx-1">{pendingPlaceholder}</code>
          </DialogDescription>
        </DialogHeader>
        
        {/* Stats */}
        <div className="flex flex-wrap gap-4 py-2 border-b">
          <div className="flex items-center gap-2 text-sm">
            <CheckSquare size={16} className="text-green-500" />
            <span>Đã chọn: <strong>{pendingReplacements.filter(r => r.selected).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <FileText size={16} className="text-blue-500" />
            <span>Placeholder: <strong>{pendingReplacements.filter(r => !r.isLinked && !r.isAutoGenerated).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <Link2 size={16} className="text-purple-500" />
            <span>Liên kết: <strong>{pendingReplacements.filter(r => r.isLinked).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <Wand2 size={16} className="text-orange-500" />
            <span>Tự sinh: <strong>{pendingReplacements.filter(r => r.isAutoGenerated).length}</strong></span>
          </div>
          <div className="ml-auto flex flex-wrap gap-2">
            <button
              onClick={() => setPendingReplacements(prev => prev.map(r => ({ ...r, selected: true })))}
              className="text-xs px-2 py-1 bg-blue-100 text-blue-700 rounded hover:bg-blue-200"
            >
              Chọn tất cả
            </button>
            <button
              onClick={() => setPendingReplacements(prev => prev.map(r => ({ ...r, selected: false })))}
              className="text-xs px-2 py-1 bg-gray-100 text-gray-700 rounded hover:bg-gray-200"
            >
              Bỏ chọn tất cả
            </button>
            <button
              onClick={() => setPendingReplacements(prev => prev.map(r => ({ ...r, selected: !r.isLinked && !r.isAutoGenerated })))}
              className="text-xs px-2 py-1 bg-purple-100 text-purple-700 rounded hover:bg-purple-200"
            >
              Loại trừ liên kết
            </button>
          </div>
        </div>

        {/* Replacement List */}
        <div className="flex-1 overflow-y-auto space-y-2 py-2">
          {pendingReplacements.map((r, idx) => (
            <div
              key={idx}
              className={`p-3 rounded-lg border transition-all ${
                r.selected 
                  ? 'border-blue-300 bg-blue-50' 
                  : 'border-gray-200 bg-gray-50 opacity-60'
              } ${r.isLinked ? 'ring-2 ring-purple-300' : ''} ${r.isAutoGenerated ? 'ring-2 ring-orange-300' : ''}`}
            >
              <div className="flex items-start gap-3">
                <button
                  onClick={() => {
                    // Cho phép chọn/bỏ chọn tất cả vị trí, kể cả vị trí gốc
                    setPendingReplacements(prev => prev.map((item, i) => 
                      i === idx ? { ...item, selected: !item.selected } : item
                    ));
                  }}
                  className="mt-1 flex-shrink-0"
                  title={r.isOriginal ? 'Vị trí gốc (có thể bỏ chọn)' : ''}
                >
                  {r.selected ? (
                    <CheckSquare size={20} className={r.isOriginal ? "text-green-600" : "text-blue-500"} />
                  ) : (
                    <Square size={20} className="text-gray-400" />
                  )}
                </button>
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 text-sm font-medium text-gray-700">
                    <FileText size={14} className="text-blue-500" />
                    {r.fileName}
                    <span className="text-xs text-gray-400">Đoạn {r.paragraphIndex + 1}</span>
                    {r.isOriginal && (
                      <span className="flex items-center gap-1 text-xs bg-green-100 text-green-700 px-2 py-0.5 rounded-full font-medium">
                        <MousePointerClick size={12} />
                        Vị trí gốc
                      </span>
                    )}
                    {r.isLinked && (
                      <span className="flex items-center gap-1 text-xs bg-purple-100 text-purple-700 px-2 py-0.5 rounded-full">
                        <Link2 size={12} />
                        Liên kết
                      </span>
                    )}
                    {r.isAutoGenerated && (
                      <span className="flex items-center gap-1 text-xs bg-orange-100 text-orange-700 px-2 py-0.5 rounded-full">
                        <Wand2 size={12} />
                        Tự sinh
                      </span>
                    )}
                  </div>
                  <p className="text-sm text-gray-600 mt-1 line-clamp-2">
                    {r.paragraphText.substring(0, 100)}
                    {r.paragraphText.length > 100 && '...'}
                  </p>
                </div>
              </div>
            </div>
          ))}
        </div>

        <DialogFooter className="border-t pt-4">
          <DialogClose asChild>
            <Button variant="outline">Hủy</Button>
          </DialogClose>
          <Button 
            onClick={() => executeReplacements(pendingReplacements, pendingPlaceholder)}
            disabled={pendingReplacements.filter(r => r.selected).length === 0}
            className="bg-gradient-to-r from-blue-600 to-indigo-600 hover:from-blue-700 hover:to-indigo-700"
          >
            <Check size={16} className="mr-2" />
            Thay thế {pendingReplacements.filter(r => r.selected).length} vị trí
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
};

export default ReplaceConfirmDialog;
