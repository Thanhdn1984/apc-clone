/**
 * Remove Vietnamese diacritics for fuzzy search
 */
export const removeVietnameseDiacritics = (str) => {
  if (!str) return '';
  return str
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // Remove combining diacritical marks
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D');
};

/**
 * Escape regex special characters
 */
export const escapeRegex = (string) => {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
};

/**
 * Unformat number (remove thousand separators)
 */
export const unformatNumber = (str) => {
  if (typeof str === 'number') return str;
  if (!str) return 0;
  return parseFloat(String(str).replace(/[.,\s]/g, ''));
};

/**
 * Convert Vietnamese name to ID
 */
export const convertVietnameseToId = (text) => {
  if (!text) return '';
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/[^a-z0-9\s]/g, '')
    .trim()
    .replace(/\s+/g, '_');
};

/**
 * Check if text is uppercase (for auto _in_hoa suffix)
 */
export const isUppercaseText = (text) => {
  if (!text) return false;
  const lettersOnly = text.replace(/[^a-zA-ZÀ-ỹ]/g, '');
  return lettersOnly.length > 0 && lettersOnly === lettersOnly.toUpperCase();
};

/**
 * Generate placeholder key with auto _in_hoa detection
 */
export const generatePlaceholderKey = (baseKey, matchedText, options = {}) => {
  if (!matchedText) return baseKey;
  
  // Check for bang_chu (text representation of numbers)
  if (options.isBangChu) {
    return `${baseKey}_bang_chu`;
  }
  
  // Check if text is uppercase
  if (isUppercaseText(matchedText)) {
    // Don't add _in_hoa if already has suffix
    if (!baseKey.endsWith('_in_hoa') && !baseKey.endsWith('_bang_chu')) {
      return `${baseKey}_in_hoa`;
    }
  }
  
  return baseKey;
};

/**
 * Check if key is auto-generated (bang_chu, in_hoa, lg_timestamp)
 */
export const isAutoGeneratedKey = (key) => {
  if (!key) return false;
  // Check for suffix-based auto-generated keys
  if (key.endsWith('_bang_chu') || key.endsWith('_in_hoa')) {
    return true;
  }
  // Check for lg_ (linked generated) pattern - lg_timestamp
  // Pattern: lg_ followed by digits (timestamp)
  if (/^lg_\d+$/.test(key) || /_lg_\d+$/.test(key) || /_\d+_lg_\d+$/.test(key)) {
    return true;
  }
  return false;
};

/**
 * Build inner pattern for text - allow spaces and punctuation between words
 * "LÂM   THỊ KIM TUYẾT" will match "LÂM THỊ KIM TUYẾT" or "LÂM  THỊ  KIM  TUYẾT"
 */
export const buildInnerPattern = (value) => {
  const normalizedValue = String(value).normalize('NFC');
  const textParts = normalizedValue.split(/[\s\p{P}]+/u).filter(Boolean);
  if (textParts.length === 0) return null;
  const SEP = '(?:[\\s\\p{P}\\u00A0])*?';
  return textParts.map(escapeRegex).join(SEP);
};

/**
 * Create numeric pattern for matching numbers with various formats
 */
export const createNumericPattern = (value) => {
  const numStr = String(value).replace(/[^\d-]/g, '');
  if (!numStr || numStr === '-') return null;
  
  const isNegative = numStr.startsWith('-');
  const digits = isNegative ? numStr.substring(1) : numStr;
  
  if (!digits) return null;
  
  // Create pattern for each digit with optional separators
  const digitParts = digits.split('').map(escapeRegex);
  const SEP = '(?:[.,\\s\\u00A0])?';
  const digitPattern = digitParts.join(SEP);
  
  if (isNegative) {
    return new RegExp(`(?:^|(?<=[^0-9]))-${SEP}${digitPattern}(?![0-9])`, 'gu');
  } else {
    return new RegExp(`(?:^|(?<=[^0-9-]))${digitPattern}(?![0-9])`, 'gu');
  }
};

/**
 * Create greedy pattern for text matching
 */
export const createGreedyPattern = (value, ignoredChars = '') => {
  const content = String(value || '').trim();
  if (!content) return null;
  
  // If pure number
  if (/^-?\d+$/.test(content)) {
    return createNumericPattern(content);
  }
  
  // If number with separators
  if (/^-?[\d.,\s]+$/.test(content) && /\d/.test(content)) {
    const numericOnly = content.replace(/[^\d-]/g, '');
    if (/^-?\d+$/.test(numericOnly)) {
      return createNumericPattern(numericOnly);
    }
  }
  
  // TEXT: split by space, comma, dot - NOT by "-"
  const separator = ignoredChars ? escapeRegex(ignoredChars) : '\\p{P}';
  const ignoredPattern = `[\\s${separator}]*?`;
  const parts = content.split(/[\s,.]+/).filter(Boolean);
  if (parts.length === 0) return null;
  
  // Vietnamese synonyms
  const synonymMap = {
    'nghìn': '(?:nghìn|ngàn)',
    'ngàn': '(?:nghìn|ngàn)',
    'lẻ': '(?:lẻ|linh)',
    'linh': '(?:lẻ|linh)'
  };
  
  const escapedParts = parts.map(part => {
    const lowerPart = part.toLowerCase();
    if (synonymMap[lowerPart]) return synonymMap[lowerPart];
    return escapeRegex(part);
  });
  
  const innerPattern = escapedParts.join(ignoredPattern);
  return new RegExp(`(?<!\\p{L})${innerPattern}(?!\\p{L})`, 'giu');
};

/**
 * Create linked pattern for matching linked field groups
 */
export const createLinkedPattern = (group, sourceValues) => {
  const { sequence, ignoredChars } = group;
  if (!sequence || !sourceValues || sourceValues.length === 0) return null;
  
  const separatorPattern = `(?:[\\s${escapeRegex(ignoredChars || ' ')}\\u00A0])*`;
  let valueIndex = 0;
  const patternParts = [];
  
  const firstItem = sequence[0];
  const lastItem = sequence[sequence.length - 1];
  const firstIsText = firstItem?.type === 'text';
  const lastIsText = lastItem?.type === 'text';
  
  for (const item of sequence) {
    let part = '';
    if (item.type === 'text') {
      const textChars = item.value.split('').map(escapeRegex);
      part = textChars.join('(?:\\s)*');
    } else if (item.type === 'field') {
      const fieldValue = sourceValues[valueIndex];
      if (fieldValue) {
        const innerPattern = buildInnerPattern(fieldValue);
        if (innerPattern) {
          part = `(${innerPattern})`;
        }
      }
      valueIndex++;
    }
    if (part) {
      patternParts.push(part);
    }
  }
  
  if (patternParts.length === 0) return null;
  
  let fullPattern = patternParts.join(separatorPattern);
  if (!firstIsText) {
    fullPattern = `(?<![\\p{L}])${fullPattern}`;
  }
  if (!lastIsText) {
    fullPattern = `${fullPattern}(?![\\p{L}])`;
  }
  
  return new RegExp(fullPattern, 'giu');
};

/**
 * Normalize text for comparison (remove punctuation, extra spaces, lowercase)
 */
export const normalizeForCompare = (str) => {
  return String(str || '')
    .normalize('NFC')
    .replace(/[\p{P}\s]+/gu, ' ')
    .trim()
    .toLowerCase();
};
