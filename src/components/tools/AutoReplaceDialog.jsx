import React from 'react';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
  DialogFooter,
  DialogClose,
} from "../../components/ui/dialog";
import { Button } from '../../components/ui/button';
import { 
  Wand2, Files, FileText, Check, CheckSquare, Square, Link2
} from 'lucide-react';

/**
 * Auto Replace Confirm Dialog - Xác nhận tự động điền hàng loạt
 */
const AutoReplaceDialog = ({ 
  showAutoReplaceConfirm, 
  setShowAutoReplaceConfirm, 
  autoReplacements, 
  setAutoReplacements,
  executeAutoReplacements
}) => {
  return (
    <Dialog open={showAutoReplaceConfirm} onOpenChange={setShowAutoReplaceConfirm}>
      <DialogContent className="sm:max-w-3xl max-h-[85vh] overflow-hidden flex flex-col">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2 text-lg">
            <Wand2 className="h-5 w-5 text-purple-500" />
            Tự động điền hàng loạt - Xác nhận
          </DialogTitle>
          <DialogDescription>
            Tìm thấy <strong className="text-blue-600">{autoReplacements.length}</strong> vị trí có thể thay thế bằng placeholder.
            Chọn các vị trí bạn muốn thay thế.
          </DialogDescription>
        </DialogHeader>
        
        {/* Stats */}
        <div className="flex flex-wrap gap-4 py-2 border-b">
          <div className="flex items-center gap-2 text-sm">
            <CheckSquare size={16} className="text-green-500" />
            <span>Đã chọn: <strong>{autoReplacements.filter(r => r.selected).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <Files size={16} className="text-blue-500" />
            <span>Placeholder: <strong>{autoReplacements.filter(r => !r.isLinked && !r.isAutoGenerated).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <Link2 size={16} className="text-purple-500" />
            <span>Liên kết: <strong>{autoReplacements.filter(r => r.isLinked).length}</strong></span>
          </div>
          <div className="flex items-center gap-2 text-sm">
            <Wand2 size={16} className="text-orange-500" />
            <span>Tự sinh: <strong>{autoReplacements.filter(r => r.isAutoGenerated).length}</strong></span>
          </div>
          <div className="ml-auto flex flex-wrap gap-2">
            <button
              onClick={() => setAutoReplacements(prev => prev.map(r => ({ ...r, selected: true })))}
              className="text-xs px-2 py-1 bg-blue-100 text-blue-700 rounded hover:bg-blue-200"
            >
              Chọn tất cả
            </button>
            <button
              onClick={() => setAutoReplacements(prev => prev.map(r => ({ ...r, selected: false })))}
              className="text-xs px-2 py-1 bg-gray-100 text-gray-700 rounded hover:bg-gray-200"
            >
              Bỏ chọn tất cả
            </button>
            <button
              onClick={() => setAutoReplacements(prev => prev.map(r => ({ ...r, selected: !r.isLinked && !r.isAutoGenerated })))}
              className="text-xs px-2 py-1 bg-purple-100 text-purple-700 rounded hover:bg-purple-200"
            >
              Loại trừ liên kết
            </button>
          </div>
        </div>

        {/* Replacement List */}
        <div className="flex-1 overflow-y-auto space-y-2 py-2">
          {autoReplacements.map((r, idx) => (
            <div
              key={r.id}
              className={`p-3 rounded-lg border transition-all ${
                r.selected 
                  ? 'border-purple-300 bg-purple-50' 
                  : 'border-gray-200 bg-gray-50 opacity-60'
              } ${r.isLinked ? 'ring-2 ring-amber-300' : ''} ${r.isAutoGenerated ? 'ring-2 ring-orange-300' : ''}`}
            >
              <div className="flex items-start gap-3">
                <button
                  onClick={() => {
                    setAutoReplacements(prev => prev.map((item, i) => 
                      i === idx ? { ...item, selected: !item.selected } : item
                    ));
                  }}
                  className="mt-1 flex-shrink-0"
                >
                  {r.selected ? (
                    <CheckSquare size={20} className="text-purple-500" />
                  ) : (
                    <Square size={20} className="text-gray-400" />
                  )}
                </button>
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 text-sm font-medium text-gray-700 flex-wrap">
                    <FileText size={14} className="text-blue-500" />
                    <span className="truncate max-w-[200px]">{r.fileName}</span>
                    <span className="text-xs text-gray-400">Đoạn {r.paragraphIndex + 1}</span>
                    <code className="bg-green-100 text-green-700 px-1.5 py-0.5 rounded text-xs font-mono">
                      {r.placeholder}
                    </code>
                    {r.isLinked && (
                      <span className="flex items-center gap-1 text-xs bg-amber-100 text-amber-700 px-2 py-0.5 rounded-full">
                        <Link2 size={12} />
                        Liên kết
                      </span>
                    )}
                    {r.isAutoGenerated && (
                      <span className="flex items-center gap-1 text-xs bg-orange-100 text-orange-700 px-2 py-0.5 rounded-full">
                        <Wand2 size={12} />
                        Tự sinh
                      </span>
                    )}
                  </div>
                  <p className="text-sm text-gray-600 mt-1">
                    "<span className="text-red-600 font-medium">{r.oldText}</span>" → <code className="bg-green-100 text-green-700 px-1 rounded">{r.placeholder}</code>
                  </p>
                  <p className="text-xs text-gray-400 mt-1 line-clamp-1">
                    ...{r.paragraphText.substring(Math.max(0, r.matchIndex - 20), r.matchIndex)}
                    <span className="bg-yellow-200 px-0.5">{r.oldText}</span>
                    {r.paragraphText.substring(r.matchIndex + r.oldText.length, r.matchIndex + r.oldText.length + 20)}...
                  </p>
                </div>
              </div>
            </div>
          ))}
        </div>

        <DialogFooter className="border-t pt-4">
          <DialogClose asChild>
            <Button variant="outline">Hủy</Button>
          </DialogClose>
          <Button 
            onClick={executeAutoReplacements}
            disabled={autoReplacements.filter(r => r.selected).length === 0}
            className="bg-gradient-to-r from-purple-600 to-indigo-600 hover:from-purple-700 hover:to-indigo-700"
          >
            <Check size={16} className="mr-2" />
            Thay thế {autoReplacements.filter(r => r.selected).length} vị trí
          </Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
};

export default AutoReplaceDialog;
